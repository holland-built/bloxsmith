// THE ASK TAB'S GENERAL LOOKUPS: find_data and api_get.
//
// The eleven fixed tools each answer one shape of question, so anything else
// ("how many top-level zones do I have") had no tool to call. find_data
// searches a list of Infoblox read-only list endpoints, and api_get reads one
// of them with the same API key the rest of the app uses.
//
// Not through Infoblox's MCP tools: on an account without the MCP Server user
// group every tools/call answers 403, and its make_*_request tools include
// writes, so one wrong allowlist entry there would be a write path.
//
// SAFETY: api_get only ever sends a GET, and only to a path that is in
// ai_catalog.json exactly as written. That file is generated by
// scripts/build-ai-catalog.py from the catalogued GET methods, without {id}
// paths and without paths that hand out tokens, bypass codes or bulk files.
// The model's text never becomes part of the URL path.

//go:embed ai_catalog.json
var aiCatalogJSON []byte

type aiCatalogEntry struct {
	Path    string `json:"path"`
	Service string `json:"service"`
	Summary string `json:"summary"`
}

var aiCatalog, aiCatalogByPath = loadAICatalog()

func loadAICatalog() ([]aiCatalogEntry, map[string]aiCatalogEntry) {
	var list []aiCatalogEntry
	if err := json.Unmarshal(aiCatalogJSON, &list); err != nil {
		panic("dashboard: bad ai_catalog.json: " + err.Error())
	}
	by := make(map[string]aiCatalogEntry, len(list))
	for _, e := range list {
		by[e.Path] = e
	}
	return list, by
}

const findDataMax = 5

var wordRE = regexp.MustCompile(`[a-z0-9]+`)

// Words that say nothing about which data source is meant.
var findDataSkip = map[string]bool{
	"how": true, "many": true, "much": true, "what": true, "which": true, "who": true, "the": true,
	"are": true, "is": true, "do": true, "does": true, "have": true, "has": true, "my": true, "our": true,
	"we": true, "you": true, "me": true, "show": true, "list": true, "all": true, "any": true, "of": true,
	"in": true, "on": true, "for": true, "and": true, "or": true, "to": true, "a": true, "an": true,
	"there": true, "get": true, "count": true, "number": true, "top": true, "level": true,
}

// findData ranks catalog entries by how many of the question's words appear
// in each one; a word in the path counts double, since the path names the
// object type and the summary often only repeats it.
func findData(query string) string {
	var words []string
	for _, w := range wordRE.FindAllString(strings.ToLower(query), -1) {
		if len(w) < 2 || findDataSkip[w] {
			continue
		}
		// "zones" should find "auth_zone"
		if len(w) > 3 && strings.HasSuffix(w, "s") {
			w = strings.TrimSuffix(w, "s")
		}
		words = append(words, w)
	}
	type scored struct {
		e     aiCatalogEntry
		score int
	}
	var hits []scored
	for _, e := range aiCatalog {
		path, sum := strings.ToLower(e.Path), strings.ToLower(e.Summary)
		n := 0
		for _, w := range words {
			if strings.Contains(path, w) {
				n += 2
			} else if strings.Contains(sum, w) {
				n++
			}
		}
		if n > 0 {
			// Most questions are about DNS, IP addresses and DHCP; without this the
			// data connector's "ETL filter" paths outrank auth_zone for "zones".
			if strings.HasPrefix(e.Path, "/api/ddi/") {
				n++
			}
			hits = append(hits, scored{e, n})
		}
	}
	if len(hits) == 0 {
		return "No Infoblox data source matched those words. Try the object's own name, " +
			"for example zone, record, subnet, lease, host, view or policy."
	}
	// stable: equal scores keep the catalog's order
	sort.SliceStable(hits, func(i, j int) bool { return hits[i].score > hits[j].score })
	type match struct {
		Path    string `json:"path"`
		Summary string `json:"summary"`
	}
	out := struct {
		Matches []match `json:"matches"`
		Next    string  `json:"next"`
	}{Next: "Call api_get with one of these paths. Add a filter to count a subset."}
	for i, h := range hits {
		if i == findDataMax {
			break
		}
		out.Matches = append(out.Matches, match{h.e.Path, h.e.Summary})
	}
	return jstr(out)
}

// apiGetLimit is how many rows one api_get fetches, the same bound get_dns uses. The exact total comes from
// page.total_size; this bound only matters when an endpoint does not report it.
const apiGetLimit = 5000

const apiGetFilterMax = 200

var apiGetFieldsRE = regexp.MustCompile(`^[A-Za-z0-9_.,]{0,200}$`)

// secretKeyRE names fields whose values are hidden from the model and the trace
// whatever endpoint they come from: belt and braces with the catalog's path
// exclusions, because a list endpoint can still embed a credential.
var secretKeyRE = regexp.MustCompile(`(?i)secret|password|passwd|token|psk|private_key|api_key`)

func (s *Service) apiGet(args map[string]any) string {
	path := aiStr(args["path"])
	if _, ok := aiCatalogByPath[path]; !ok {
		return fmt.Sprintf("%q is not a readable data source. Call find_data first and use a path it returns, exactly as written.", path)
	}
	filter, fields := aiStr(args["filter"]), aiStr(args["fields"])
	if len(filter) > apiGetFilterMax {
		return fmt.Sprintf("That filter is not accepted: it is longer than %d characters.", apiGetFilterMax)
	}
	if !apiGetFieldsRE.MatchString(fields) {
		return "Those fields are not accepted: use field names separated by commas, for example fqdn,view."
	}
	params := map[string]string{"_limit": fmt.Sprint(apiGetLimit), "_is_total_size_needed": "true"}
	if filter != "" {
		params["_filter"] = filter
	}
	if fields != "" {
		params["_fields"] = fields
	}
	rows, body, err := s.Rest.GetPageStrict(path, params)
	if err != nil {
		return aiLookupFailed("records from "+path, aiUpstreamDetail(err))
	}
	maps := make([]map[string]any, 0, len(rows))
	for _, r := range rows {
		maps = append(maps, hideSecrets(asMap(r)).(map[string]any))
	}
	total := pageTotalSize(body, -1)
	if total < 0 && len(maps) >= apiGetLimit {
		// No total and a full page: the real count is unknown, so no total_count
		// field at all, rather than one the model would take as exact.
		sample := capMaps(maps, aiSampleCap)
		return jstr(struct {
			Summary   string           `json:"summary"`
			Untrusted string           `json:"UNTRUSTED_DATA_NOTICE"`
			AtLeast   int              `json:"total_count_at_least"`
			Returned  int              `json:"returned"`
			Truncated bool             `json:"truncated"`
			Sample    []map[string]any `json:"sample"`
		}{
			Summary: fmt.Sprintf("At least %d records exist; Infoblox did not report the exact total. "+
				"The %d below are a sample, not the full list.", apiGetLimit, len(sample)),
			Untrusted: untrustedNotice, AtLeast: apiGetLimit, Returned: len(sample), Truncated: true, Sample: sample,
		})
	}
	if total < 0 {
		// fewer rows than asked for: the page holds everything
		total = len(maps)
	}
	return jstr(cappedPayloadWithTotal(maps, aiSampleCap, total, "records"))
}

// hideSecrets replaces the value of every secret-looking key, at any depth,
// including maps inside lists inside lists.
func hideSecrets(v any) any {
	switch t := v.(type) {
	case map[string]any:
		for k, x := range t {
			if secretKeyRE.MatchString(k) {
				t[k] = "[hidden]"
			} else {
				t[k] = hideSecrets(x)
			}
		}
	case []any:
		for i, x := range t {
			t[i] = hideSecrets(x)
		}
	}
	return v
}
